function getCertId() {
  const params = new URLSearchParams(window.location.search);
  return params.get('id');
}

function renderCertificate(cert) {
  const content = document.getElementById('certContent');
  const notFound = document.getElementById('certNotFound');

  document.title = cert.title + ' | JAO';

  const badgeClass = (cert.type === 'Awardee' || cert.type === 'Recognition') ? 'cert-badge achievement' : 'cert-badge';

  let imageHtml = '';
  if (cert.image) {
    imageHtml =
      '<div class="cert-detail-image">' +
      '<img src="' + cert.image + '" alt="' + cert.title + '">' +
      '</div>';
  }

  let actionsHtml = '';
  if (cert.verify) {
    actionsHtml =
      '<div class="project-detail-actions">' +
      '<a href="' + cert.verify + '" target="_blank" rel="noopener noreferrer" class="btn">Verify Certificate</a>' +
      '</div>';
  }

  content.innerHTML =
    '<article class="project-detail-card">' +
    '<span class="' + badgeClass + '">' + cert.type + '</span>' +
    '<h1>' + cert.title + '</h1>' +
    '<p class="project-detail-subtitle">' + cert.org + '</p>' +
    '<p class="cert-year">' + cert.year + (cert.venue ? ' · ' + cert.venue : '') + '</p>' +
    '<p class="project-detail-desc">' + cert.description + '</p>' +
    imageHtml +
    actionsHtml +
    '</article>';

  notFound.style.display = 'none';
  content.style.display = 'block';
}

const certId = getCertId();
const certContent = document.getElementById('certContent');
const certNotFound = document.getElementById('certNotFound');

if (certId && certificatesData[certId]) {
  renderCertificate(certificatesData[certId]);
} else {
  certContent.style.display = 'none';
  certNotFound.style.display = 'block';
}

const menuBtn = document.getElementById('menuBtn');
const navLinks = document.querySelector('.nav-links');

if (menuBtn && navLinks) {
  menuBtn.addEventListener('click', function () {
    navLinks.classList.toggle('active');
  });

  document.querySelectorAll('.nav-links a').forEach(function (link) {
    link.addEventListener('click', function () {
      navLinks.classList.remove('active');
    });
  });
}
